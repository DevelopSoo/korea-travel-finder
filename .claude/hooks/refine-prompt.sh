#!/usr/bin/env bash
# UserPromptSubmit hook: 사용자의 요청을 실행 전에 "구체화 → 승인" 하도록 유도한다.
# stdout 은 그대로 Claude 의 컨텍스트에 추가된다.
set -euo pipefail

input=$(cat)
prompt=$(printf '%s' "$input" | jq -r '.prompt // ""')

# 이스케이프: ">" 로 시작하면 정제 없이 즉시 실행
case "$prompt" in
  '>'*) exit 0 ;;
esac

# 슬래시 커맨드는 건너뜀
case "$prompt" in
  '/'*) exit 0 ;;
esac

# 짧은 응답("ㅇㅇ", "승인", "계속", "2번")은 앞선 승인 질문에 대한 답이므로 건너뜀
if [ "$(printf '%s' "$prompt" | wc -m | tr -d ' ')" -lt 12 ]; then
  exit 0
fi

cat <<'PROTOCOL'
<prompt-refinement-protocol>
위 사용자 요청은 **바로 실행하지 않는다.** 아래 절차를 따른다.

1. 요청을 아래 형식으로 재구성해 출력한다.

   ## ▸ 정리된 요청
   - 목표: (사용자가 최종적으로 얻으려는 결과)
   - 범위: (건드릴 것 / 건드리지 않을 것)
   - 제약: (스택·기존 컨벤션·디자인/기획 문서 규칙 등 실제 확인한 것만)
   - 완료 조건: (무엇이 되면 끝인가)
   - 내가 정한 기본값: (취향·관행적 선택은 묻지 말고 여기에 한 줄씩. 없으면 생략)

2. 이어서 AskUserQuestion 으로 승인을 받는다. 선택지:
   - "승인 — 이대로 진행" (첫 번째, Recommended)
   - "수정 — 다시 정리" (사용자가 Other 로 수정 사항을 적을 수 있다)
   - 해석이 갈려 결과물이 달라지는 지점이 있으면 그 갈림길도 같은 질문에 최대 2개까지 추가한다.

3. 승인 전에는 파일을 수정하거나 명령을 실행하지 않는다.
   (파악을 위한 읽기·검색은 허용)

4. "수정" 을 받으면 사용자 의견을 반영해 1→2 를 다시 수행한다.
   승인을 받으면 그때 작업을 실행한다.

5. 사용자의 원래 요청 범위를 임의로 넓히거나 좁히지 않는다.
   정제는 "명확하게" 만드는 것이지 "더 크게" 만드는 것이 아니다.

예외: 단순 질문·설명 요청(코드 변경이 없는 것)은 재구성·승인 없이 바로 답한다.
</prompt-refinement-protocol>
PROTOCOL
